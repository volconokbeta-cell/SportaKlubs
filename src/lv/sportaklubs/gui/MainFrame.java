    /**
     * Noformē GUI Builder izveidotu tabulu un pievieno rindas izvēles apstrādi.
     *
     * @param table    tabula
     * @param onSelect darbība, kas tiek izpildīta, izvēloties rindu (var būt null)
     * @return tabulas modelis (kolonnas definētas GUI Builder īpašībā model)
     */
    private DefaultTableModel prepareTable(JTable table, java.util.function.IntConsumer onSelect) {
        Ui.setupTable(table);
        if (onSelect != null) {
            table.getSelectionModel().addListSelectionListener(e -> {
                if (!e.getValueIsAdjusting() && table.getSelectedRow() >= 0 && !loading) {
                    onSelect.accept(table.getSelectedRow());
                }
            });
        }
        return (DefaultTableModel) table.getModel();
    }

