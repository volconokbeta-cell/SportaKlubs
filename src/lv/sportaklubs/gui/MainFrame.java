    /** Pārbauda reģistrācijas datus un izveido klienta kontu (FP-01). */
    private void register() {
        String pass = new String(regTxtPass.getPassword());
        LocalDate birth = Validator.parseDate(regTxtBirth.getText());
        try {
            if (!Validator.isNotEmpty(regTxtFirst.getText()) || !Validator.isNotEmpty(regTxtLast.getText())
                    || !Validator.isNotEmpty(regTxtUser.getText())) {
                Ui.error(dlgRegister, "Lūdzu, aizpildiet visus obligātos laukus!");
            } else if (!Validator.isValidPhone(regTxtPhone.getText())) {
                Ui.error(dlgRegister, "Nepareizs tālruņa numurs! Jābūt 8 cipariem, sākot ar 2 vai 6.");
            } else if (!Validator.isValidEmail(regTxtEmail.getText())) {
                Ui.error(dlgRegister, "Nepareizs e-pasta formāts!");
            } else if (Validator.isNotEmpty(regTxtBirth.getText()) && (birth == null || birth.isAfter(LocalDate.now()))) {
                Ui.error(dlgRegister, "Nepareizs dzimšanas datums! Formāts: gggg-mm-dd.");
            } else if (!Validator.isValidPassword(pass)) {
                Ui.error(dlgRegister, "Parolei jābūt vismaz 6 simbolus garai!");
            } else if (!pass.equals(new String(regTxtPass2.getPassword()))) {
                Ui.error(dlgRegister, "Paroles nesakrīt!");
            } else if (new UserDAO().usernameExists(regTxtUser.getText())) {
                Ui.error(dlgRegister, "Šāds lietotājvārds jau ir aizņemts!");
            } else if (clientDao.emailExists(regTxtEmail.getText(), 0)) {
                Ui.error(dlgRegister, "Klients ar šādu e-pastu jau ir reģistrēts!");
            } else {
                Client c = new Client(0, null, regTxtFirst.getText(), regTxtLast.getText(), regTxtPhone.getText(),
                        regTxtEmail.getText(), birth);
                new UserDAO().register(regTxtUser.getText(), pass, c);
                Ui.info(dlgRegister, "Reģistrācija ir veiksmīga! Tagad varat pieslēgties.");
                dlgRegister.setVisible(false);
            }
        } catch (SQLException e) {
            Ui.dbError(dlgRegister, e);
        }
    }

