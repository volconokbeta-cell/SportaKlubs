    /**
     * Nolasa nodarbības ar filtru pēc datuma un trenera.
     *
     * @param fromSearch true, ja ielāde notiek pēc pogas "Meklēt"
     */
    private void reloadTrainings(boolean fromSearch) {
        if (loading) {
            return;
        }
        LocalDate date = trgTxtSearch.getText().isBlank() ? null : Validator.parseDate(trgTxtSearch.getText());
        if (!trgTxtSearch.getText().isBlank() && date == null) {
            Ui.error(dlgTrainings, "Nepareizs datums! Formāts: gggg-mm-dd.");
            return;
        }
        loading = true;
        try {
            trgModel.setRowCount(0);
            int idx = trgCmbFilter.getSelectedIndex();
            int trainerId = idx <= 0 ? 0 : trgTrainers.get(idx - 1).getId();
            trgRows = trainingDao.search(date, trainerId);
            for (Training t : trgRows) {
                trgModel.addRow(new Object[]{t.getId(), t.getName(), t.getTrainerName(),
                    t.getStartTime().toLocalDate().toString(), t.getStartTime().toLocalTime().toString(),
                    t.getDurationMin() + " min", t.getHall(), t.getFreeSpots() + " / " + t.getMaxParticipants()});
            }
            if (fromSearch && trgModel.getRowCount() == 0) {
                Ui.info(dlgTrainings, "Pēc norādītajiem kritērijiem nekas netika atrasts.");
            }
        } catch (SQLException e) {
            Ui.dbError(dlgTrainings, e);
        } finally {
            loading = false;
        }
    }

