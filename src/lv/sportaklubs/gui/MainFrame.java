    /**
     * Nolasa maksājumus vai neapmaksātos abonementus (atkarībā no filtra).
     *
     * @param fromSearch true, ja ielāde notiek pēc pogas "Meklēt"
     */
    private void reloadPayments(boolean fromSearch) {
        loading = true;
        try {
            payModel.setRowCount(0);
            String text = payTxtSearch.getText().trim().toLowerCase();
            if (unpaidView()) {
                payModel.setColumnIdentifiers(new Object[]{"ID", "Klients", "Abonements", "Cena", "Samaksāts",
                    "Jāpiemaksā"});
                payUnpaid = membershipDao.getUnpaid();
                for (Membership m : payUnpaid) {
                    double paid = paymentDao.getPaidAmount(m.getId());
                    if (m.getClientName().toLowerCase().contains(text)) {
                        payModel.addRow(new Object[]{m.getId(), m.getClientName(), m.getType(), fmt(m.getPrice()),
                            fmt(paid), fmt(m.getPrice() - paid)});
                    }
                }
            } else {
                payModel.setColumnIdentifiers(new Object[]{"ID", "Klients", "Abonements", "Summa", "Datums", "Veids"});
                payRows = paymentDao.search(payTxtSearch.getText());
                for (Payment p : payRows) {
                    payModel.addRow(new Object[]{p.getId(), p.getClientName(), "#" + p.getMembershipId(),
                        fmt(p.getAmount()), p.getPayDate().toString(), p.getMethod()});
                }
            }
            Ui.setupTable(payTblData);
            if (fromSearch && payModel.getRowCount() == 0) {
                Ui.info(dlgPayments, "Pēc norādītajiem kritērijiem nekas netika atrasts.");
            }
        } catch (SQLException e) {
            Ui.dbError(dlgPayments, e);
        } finally {
            loading = false;
        }
    }

    /**
     * Formatē summu ar diviem cipariem aiz komata.
     *
     * @param d summa
     * @return formatēta summa
     */
    private static String fmt(double d) {
        return String.format("%.2f", d);
    }

    /**
     * Izvēlas klientu un abonementu maksājumu loga nolaižamajos sarakstos.
     *
     * @param clientId     klienta ID
     * @param membershipId abonementa ID
     */
    private void selectPaymentClient(int clientId, int membershipId) {
        for (int i = 0; i < payCmbClient.getItemCount(); i++) {
            if (payCmbClient.getItemAt(i).getId() == clientId) {
                payCmbClient.setSelectedIndex(i);
            }
        }
        for (int i = 0; i < payCmbMembership.getItemCount(); i++) {
            if (payCmbMembership.getItemAt(i).getId() == membershipId) {
                payCmbMembership.setSelectedIndex(i);
            }
        }
    }

    /**
     * Ievieto izvēlētās rindas datus maksājumu loga ievadlaukos.
     *
     * @param row rindas numurs tabulā
     */
    private void fillPaymentForm(int row) {
        if (unpaidView()) {
            int id = (Integer) payModel.getValueAt(row, 0);
            for (Membership m : payUnpaid) {
                if (m.getId() == id) {
                    selectPaymentClient(m.getClientId(), m.getId());
                    payTxtAmount.setText((String) payModel.getValueAt(row, 5));
                    payTxtDate.setText(LocalDate.now().toString());
                }
            }
        } else {
            Payment p = payRows.get(row);
            selectPaymentClient(p.getClientId(), p.getMembershipId());
            payTxtAmount.setText(fmt(p.getAmount()));
            payTxtDate.setText(p.getPayDate().toString());
            payCmbMethod.setSelectedItem(p.getMethod());
        }
    }

    /** Notīra maksājumu loga ievadlaukus (datums – šodiena). */
    private void clearPaymentForm() {
        payTxtAmount.setText("");
        payTxtDate.setText(LocalDate.now().toString());
        payCmbMethod.setSelectedIndex(0);
        payTblData.clearSelection();
    }

    /**
     * Reģistrē jaunu maksājumu vai saglabā izvēlētā maksājuma izmaiņas.
     *
     * @param update true – labot izvēlēto, false – reģistrēt jaunu
     */
    private void savePayment(boolean update) {
        Integer id = 0;
        if (update) {
            if (unpaidView()) {
                Ui.warn(dlgPayments, "Labot var tikai sarakstā “Visi maksājumi”.");
                return;
            }
            if ((id = Ui.selectedId(dlgPayments, payTblData, "maksājumu")) == null) {
                return;
            }
        }
        Client c = (Client) payCmbClient.getSelectedItem();
        Membership m = (Membership) payCmbMembership.getSelectedItem();
        double amount = Validator.parsePositive(payTxtAmount.getText());
        LocalDate date = Validator.parseDate(payTxtDate.getText());
        if (c == null || m == null) {
            Ui.error(dlgPayments, "Lūdzu, izvēlieties klientu un abonementu!");
        } else if (amount <= 0) {
            Ui.error(dlgPayments, "Summai jābūt pozitīvam skaitlim!");
        } else if (date == null) {
            Ui.error(dlgPayments, "Nepareizs datums! Formāts: gggg-mm-dd.");
        } else {
            Payment p = new Payment(id, c.getId(), m.getId(), amount, date, (String) payCmbMethod.getSelectedItem());
            try {
                if (update) {
                    paymentDao.update(p);
                    Ui.info(dlgPayments, "Maksājuma dati saglabāti!");
                } else {
                    paymentDao.add(p);
                    Ui.info(dlgPayments, "Maksājums reģistrēts!");
                }
                clearPaymentForm();
                reloadPayments(false);
            } catch (SQLException e) {
                Ui.dbError(dlgPayments, e);
            }
        }
    }

    /** Dzēš izvēlēto maksājumu pēc apstiprinājuma. */
    private void deletePayment() {
        if (unpaidView()) {
            Ui.warn(dlgPayments, "Dzēst var tikai sarakstā “Visi maksājumi”.");
            return;
        }
        Integer id = Ui.selectedId(dlgPayments, payTblData, "maksājumu");
        if (id != null && Ui.confirm(dlgPayments, "Vai tiešām dzēst maksājumu?")) {
            try {
                paymentDao.delete(id);
                Ui.info(dlgPayments, "Maksājums dzēsts!");
                clearPaymentForm();
                reloadPayments(false);
            } catch (SQLException e) {
                Ui.dbError(dlgPayments, e);
            }
        }
    }

