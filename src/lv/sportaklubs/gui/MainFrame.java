    /**
     * Nolasa klientus pēc meklēšanas teksta un filtra.
     *
     * @param fromSearch true, ja ielāde notiek pēc pogas "Meklēt"
     */
    private void reloadClients(boolean fromSearch) {
        loading = true;
        try {
            cliModel.setRowCount(0);
            LocalDate today = LocalDate.now();
            for (Client c : clientDao.search(cliTxtSearch.getText(), (String) cliCmbFilter.getSelectedItem(), today)) {
                Membership m = membershipDao.getActive(c.getId(), today);
                cliModel.addRow(new Object[]{c.getId(), c.getFirstName(), c.getLastName(), c.getPhone(), c.getEmail(),
                    c.getBirthDate() == null ? "" : c.getBirthDate().toString(),
                    m == null ? "nav aktīva" : m.getEndDate().toString()});
            }
            if (fromSearch && cliModel.getRowCount() == 0) {
                Ui.info(dlgClients, "Pēc norādītajiem kritērijiem nekas netika atrasts.");
            }
        } catch (SQLException e) {
            Ui.dbError(dlgClients, e);
        } finally {
            loading = false;
        }
    }

