    /**
     * Pievieno jaunu treneri vai saglabā izvēlētā trenera izmaiņas.
     *
     * @param update true – labot izvēlēto, false – pievienot jaunu
     */
    private void saveTrainer(boolean update) {
        Integer id = 0;
        if (update && (id = Ui.selectedId(dlgTrainers, trnTblData, "treneri")) == null) {
            return;
        }
        if (!Validator.isNotEmpty(trnTxtFirst.getText()) || !Validator.isNotEmpty(trnTxtLast.getText())
                || !Validator.isNotEmpty(trnTxtSpec.getText())) {
            Ui.error(dlgTrainers, "Lūdzu, aizpildiet vārdu, uzvārdu un specializāciju!");
            return;
        }
        if (Validator.isNotEmpty(trnTxtPhone.getText()) && !Validator.isValidPhone(trnTxtPhone.getText())) {
            Ui.error(dlgTrainers, "Nepareizs tālruņa numurs!");
            return;
        }
        Trainer t = new Trainer(id, trnTxtFirst.getText(), trnTxtLast.getText(), trnTxtSpec.getText(),
                trnTxtPhone.getText());
        try {
            if (update) {
                trainerDao.update(t);
                Ui.info(dlgTrainers, "Trenera dati saglabāti!");
            } else {
                trainerDao.add(t);
                Ui.info(dlgTrainers, "Treneris pievienots!");
            }
            clearTrainerForm();
            reloadTrainers(false);
        } catch (SQLException e) {
            Ui.dbError(dlgTrainers, e);
        }
    }

    /** Dzēš izvēlēto treneri, ja viņam nav piesaistītu nodarbību. */
    private void deleteTrainer() {
        Integer id = Ui.selectedId(dlgTrainers, trnTblData, "treneri");
        if (id == null) {
            return;
        }
        try {
            if (trainerDao.hasTrainings(id)) {
                Ui.error(dlgTrainers, "Treneri nevar dzēst, jo viņam ir piesaistītas nodarbības!");
                return;
            }
            if (Ui.confirm(dlgTrainers, "Vai tiešām dzēst treneri?")) {
                trainerDao.delete(id);
                Ui.info(dlgTrainers, "Treneris dzēsts!");
                clearTrainerForm();
                reloadTrainers(false);
            }
        } catch (SQLException e) {
            Ui.dbError(dlgTrainers, e);
        }
    }

