    /**
     * Parāda pieslēgšanās logu (vai reģistrācijas logu, ja lietotājs to izvēlas).
     * Ja lietotājs aizver pieslēgšanās logu bez pieslēgšanās, programma beidz darbu.
     */
    public void showLogin() {
        setVisible(false);
        while (true) {
            loginSuccess = false;
            registerRequested = false;
            logTxtPass.setText("");
            dlgLogin.pack();
            dlgLogin.setLocationRelativeTo(null);
            dlgLogin.getRootPane().setDefaultButton(logBtnLogin);
            dlgLogin.setVisible(true);
            if (loginSuccess) {
                break;
            }
            if (!registerRequested) {
                System.exit(0);
            }
            clearRegisterForm();
            dlgRegister.pack();
            dlgRegister.setLocationRelativeTo(null);
            dlgRegister.setVisible(true);
        }
        logTxtUser.setText("");
        showMenuForRole();
        setVisible(true);
    }

    /** Pārbauda pieslēgšanās datus un saglabā pieslēgušos lietotāju sesijā (FP-02). */
    private void login() {
        String user = logTxtUser.getText();
        String pass = new String(logTxtPass.getPassword());
        if (!Validator.isNotEmpty(user) || pass.isEmpty()) {
            Ui.error(dlgLogin, "Lūdzu, ievadiet lietotājvārdu un paroli!");
            return;
        }
        try {
            User u = new UserDAO().login(user, pass);
            if (u == null) {
                Ui.error(dlgLogin, "Nepareizs lietotājvārds vai parole!");
                logTxtPass.setText("");
                return;
            }
            Session.userId = u.getId();
            Session.role = u.getRole();
            Session.username = u.getUsername();
            if (!u.isAdmin()) {
                Client c = clientDao.getByUserId(u.getId());
                Session.clientId = c == null ? -1 : c.getId();
            }
            Ui.info(dlgLogin, "Ieeja ir veiksmīga!");
            loginSuccess = true;
            dlgLogin.setVisible(false);
        } catch (SQLException e) {
            Ui.dbError(dlgLogin, e);
        }
    }

