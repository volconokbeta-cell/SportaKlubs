    /**
     * Pievieno jaunu nodarbību vai saglabā izvēlētās nodarbības izmaiņas.
     *
     * @param update true – labot izvēlēto, false – pievienot jaunu
     */
    private void saveTraining(boolean update) {
        Integer id = 0;
        if (update && (id = Ui.selectedId(dlgTrainings, trgTblData, "nodarbību")) == null) {
            return;
        }
        Trainer trainer = (Trainer) trgCmbTrainer.getSelectedItem();
        LocalDate date = Validator.parseDate(trgTxtDate.getText());
        LocalTime time;
        try {
            time = LocalTime.parse(trgTxtTime.getText().trim());
        } catch (DateTimeParseException e) {
            time = null;
        }
        int duration = (int) Validator.parsePositive(trgTxtDuration.getText());
        int places = (int) Validator.parsePositive(trgTxtPlaces.getText());
        if (!Validator.isNotEmpty(trgTxtName.getText()) || !Validator.isNotEmpty(trgTxtHall.getText())
                || trainer == null) {
            Ui.error(dlgTrainings, "Lūdzu, aizpildiet nosaukumu, zāli un izvēlieties treneri!");
        } else if (date == null || time == null) {
            Ui.error(dlgTrainings, "Nepareizs datums vai laiks! Formāts: gggg-mm-dd un hh:mm.");
        } else if (!update && LocalDateTime.of(date, time).isBefore(LocalDateTime.now())) {
            Ui.error(dlgTrainings, "Nodarbības laiks nevar būt pagātnē!");
        } else if (duration <= 0 || places <= 0) {
            Ui.error(dlgTrainings, "Ilgumam un vietu skaitam jābūt pozitīviem veseliem skaitļiem!");
        } else {
            Training t = new Training(id, trgTxtName.getText(), trainer.getId(), LocalDateTime.of(date, time),
                    duration, trgTxtHall.getText(), places);
            try {
                if (trainingDao.isHallBusy(t, id)) {
                    Ui.error(dlgTrainings, "Zāle šajā laikā jau ir aizņemta ar citu nodarbību!");
                    return;
                }
                if (update) {
                    trainingDao.update(t);
                } else {
                    trainingDao.add(t);
                }
                Ui.info(dlgTrainings, "Nodarbība saglabāta!");
                clearTrainingForm();
                reloadTrainings(false);
            } catch (SQLException e) {
                Ui.dbError(dlgTrainings, e);
            }
        }
    }

