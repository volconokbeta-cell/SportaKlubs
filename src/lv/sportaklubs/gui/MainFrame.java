    /** Nolasa pieslēgtā klienta abonementu, maksājumus un nākamo nodarbību grafiku. */
    private void loadMyAccount() {
        int clientId = Session.clientId;
        try {
            Membership m = membershipDao.getActive(clientId, LocalDate.now());
            accLblMembership.setText(m == null ? "Jums vēl nav aktīva abonementa."
                    : m.getType() + " abonements  |  " + m.getStartDate() + " – " + m.getEndDate()
                    + "  |  Statuss: " + m.getStatus());
            accPayModel.setRowCount(0);
            for (Payment p : paymentDao.getByClient(clientId)) {
                accPayModel.addRow(new Object[]{p.getPayDate().toString(), String.format("%.2f EUR", p.getAmount()),
                    p.getMethod(), "#" + p.getMembershipId()});
            }
            accTrModel.setRowCount(0);
            accTrainings = new ArrayList<>();
            Set<Integer> mine = bookingDao.getTrainingIds(clientId);
            for (Training t : trainingDao.search(null, 0)) {
                if (t.getStartTime().isAfter(LocalDateTime.now())) {
                    accTrainings.add(t);
                    accTrModel.addRow(new Object[]{t.getName(), t.getTrainerName(),
                        t.getStartTime().toLocalDate() + " " + t.getStartTime().toLocalTime(), t.getHall(),
                        t.getFreeSpots() + " / " + t.getMaxParticipants(), mine.contains(t.getId()) ? "Jā" : "–"});
                }
            }
        } catch (SQLException e) {
            Ui.dbError(dlgMyAccount, e);
        }
    }

    /** @return grafikā izvēlētā nodarbība vai null (tiek parādīts brīdinājums) */
    private Training selectedAccountTraining() {
        int row = accTblTrainings.getSelectedRow();
        if (row < 0) {
            Ui.warn(dlgMyAccount, "Lūdzu, izvēlieties nodarbību grafikā!");
            return null;
        }
        return accTrainings.get(row);
    }

    /** Pieraksta klientu izvēlētajai nodarbībai (FP-10). */
    private void bookTraining() {
        Training t = selectedAccountTraining();
        if (t == null) {
            return;
        }
        try {
            Booking.Result r = bookingDao.book(Session.clientId, t.getId(), LocalDateTime.now());
            switch (r) {
                case SUCCESS: Ui.info(dlgMyAccount, "Jūs esat pierakstīts nodarbībai “" + t.getName() + "”!"); break;
                case NO_MEMBERSHIP: Ui.error(dlgMyAccount, "Jums nav aktīva abonementa nodarbības dienā!"); break;
                case NO_FREE_SPOTS: Ui.error(dlgMyAccount, "Nodarbībā vairs nav brīvu vietu!"); break;
                case ALREADY_BOOKED: Ui.warn(dlgMyAccount, "Jūs jau esat pierakstīts šai nodarbībai!"); break;
                default: Ui.error(dlgMyAccount, "Nodarbība jau ir sākusies vai notikusi!");
            }
            loadMyAccount();
        } catch (SQLException e) {
            Ui.dbError(dlgMyAccount, e);
        }
    }

    /** Atceļ klienta pierakstu izvēlētajai nodarbībai pēc apstiprinājuma. */
    private void cancelBooking() {
        Training t = selectedAccountTraining();
        if (t == null || !Ui.confirm(dlgMyAccount, "Vai tiešām atcelt pierakstu nodarbībai “" + t.getName() + "”?")) {
            return;
        }
        try {
            if (bookingDao.cancel(Session.clientId, t.getId())) {
                Ui.info(dlgMyAccount, "Pieraksts atcelts.");
            } else {
                Ui.warn(dlgMyAccount, "Jūs neesat pierakstīts šai nodarbībai!");
            }
            loadMyAccount();
        } catch (SQLException e) {
            Ui.dbError(dlgMyAccount, e);
        }
    }

